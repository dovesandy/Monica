#include <iostream>
using namespace std;

int main() {
  // 基本整数类型
  int age = 18;
  short smallNumber = 100;
  long largeNumber = 1234567890;

  // 浮点类型
  float pi = 3.14f;
  double e = 2.718281828459;
  long double preciseValue = 3.14159265358979323846L;

  // 字符类型
  char initial = 'A';
  wchar_t wideChar = L'你';

  // 布尔类型
  bool isStudent = true;

  return 0;
}